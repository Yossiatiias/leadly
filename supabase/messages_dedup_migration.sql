-- ── מניעת הודעות כפולות מהוואטסאפ ──────────────────────────────────────────
-- הבדיקה הקיימת בקוד (SELECT ואז INSERT) לא מגינה מפני שני webhook-ים
-- שמגיעים כמעט בו-זמנית עבור אותה הודעה (Green API שולח לפעמים כפילות
-- ב-retry). בלי אילוץ ברמת המסד, שני הבקשות עלולות לעבור את הבדיקה
-- ולגרום לבוט לענות פעמיים לאותה הודעה, או ליצור ליד/תור כפול.
--
-- אינדקס ייחודי חלקי (רק כש-whatsapp_message_id לא NULL, כי הודעות
-- שנשלחות ידנית ע"י נציג/בוט לא תמיד נושאות מזהה כזה) הופך את זה
-- לבלתי אפשרי ברמת המסד עצמו — הניסיון השני להכניס פשוט נכשל.

CREATE UNIQUE INDEX IF NOT EXISTS messages_whatsapp_message_id_unique
  ON messages (whatsapp_message_id)
  WHERE whatsapp_message_id IS NOT NULL;
